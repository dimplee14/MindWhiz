<?php
// Page 4: Memorization screen showing randomized words with a countdown timer.
// Security: requires active session (student + attempt), regenerates CSRF if missing, blocks re-entry via flags.
require_once __DIR__ . '/../backend/dbconnect/db.php';
require_once __DIR__ . '/../backend/config/test_config.php';
session_start();
// Ensure CSRF token exists for subsequent actions (e.g., transitions/requests)
if (empty($_SESSION['csrf_token'])) {
  try { $_SESSION['csrf_token'] = bin2hex(random_bytes(32)); } catch (Exception $e) { $_SESSION['csrf_token'] = bin2hex(openssl_random_pseudo_bytes(32)); }
}

// Prevent caching so browser back/restore forces a reload and server checks flags
// This works with mark_phase.php logic: when user tries to navigate back after timer expires,
// browser won't show cached page but will reload, triggering flag checks below to redirect appropriately
header('Cache-Control: no-store, no-cache, must-revalidate, max-age=0');
header('Pragma: no-cache');
header('Expires: 0');

// Require authenticated student and an active attempt; otherwise restart flow
// This ensures user came from page2.php (registration) and page3.php (start test)
if (empty($_SESSION['student_id']) || empty($_SESSION['attempt_id'])) {
  $_SESSION['error'] = 'Session expired. Please re-enter details.';
  header('Location: page2.php');
  exit();
}

$attempt_id = (int) $_SESSION['attempt_id'];

// If memorize was previously marked expired for this attempt, don't allow re-entry (session-level flag)
// This flag is set by mark_phase.php (called via sendBeacon from page4.js when timer expires)
// Prevents user from using browser back button to return to memorization phase
if (isset($_SESSION['attempt_state'][$attempt_id]['memorize_expired']) && $_SESSION['attempt_state'][$attempt_id]['memorize_expired']) {
  header('Location: page6.php');
  exit();
}

// Also check persistent DB flag table (attempt_flags) so user cannot bypass by switching browsers
// This provides database-level protection in addition to session-level flag above
// mark_phase.php creates/updates this table when phases expire
// If memorize_expired: redirect to page6.php (recall phase)
// If recall_expired: redirect to page7.php (review answers)
$flag_stmt = mysqli_prepare($conn, "SELECT memorize_expired, recall_expired FROM attempt_flags WHERE attempt_id = ? LIMIT 1");
mysqli_stmt_bind_param($flag_stmt, "i", $attempt_id);
mysqli_stmt_execute($flag_stmt);
$flag_res = mysqli_stmt_get_result($flag_stmt);
$flag_row = mysqli_fetch_assoc($flag_res);
if ($flag_row) {
  if (!empty($flag_row['memorize_expired'])) {
    header('Location: page6.php');
    exit();
  } 
  if (!empty($flag_row['recall_expired'])) {
    header('Location: page7.php');
    exit();
  }
}
// Fetch the randomized words generated by generate_words.php (called from page3.php)
// Words are stored as JSON in attempt_words table during test initialization
$words_sql = "SELECT words FROM attempt_words WHERE attempt_id = ? LIMIT 1";
$stmt = mysqli_prepare($conn, $words_sql);
mysqli_stmt_bind_param($stmt, "i", $attempt_id);
mysqli_stmt_execute($stmt);
$res = mysqli_stmt_get_result($stmt);
$row = mysqli_fetch_assoc($res);

if (!$row || empty($row['words'])) {
  $_SESSION['error'] = 'Words not found for this attempt.';
  header('Location: ../page2.php');
  exit();
}

// Decode JSON words array and validate count matches TOTAL_WORDS from test_config.php
$words = json_decode($row['words'], true);
if (!is_array($words) || count($words) !== TOTAL_WORDS) $words = [];

// Localization: Display UI text in user's selected language (set in page2.php registration form)
// Supports English (eng) and Gujarati (guj)
$lang = $_SESSION['language'] ?? 'eng';
$txt = [
  'eng' => [
    'heading' => '🧠 Remember the Words Below',
    'instruction' => 'To pass, remember any one vertical line from the 3 lines.',
    'button' => 'Recall'
  ],
  'guj' => [
    'heading' => '🧠 નીચેના શબ્દો યાદ રાખો',
    'instruction' => 'પાસ થવા માટે 3 line માંથી કોઈ પણ ઊભી line યાદ રાખો.',
    'button' => 'યાદ કરો'
  ]
];
$t = $txt[$lang] ?? $txt['eng'];
