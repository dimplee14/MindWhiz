    // Inject server-side data for client timer and rendering logic
    // WORDS: Array of randomized words to display in boxes
    // MEMORIZE_TIME: Countdown timer duration (seconds) from test_config.php
    // ATTEMPT_ID: Used by page4.js to call mark_phase.php when timer expires
